/**
 * Build-time Content-Security-Policy for Netlify.
 *
 * netlify.toml cannot read environment variables, so the CSP header (which
 * needs the API host from VITE_API_URL and the hash of the inline theme
 * script in index.html) is written to dist/_headers after the build. Netlify
 * merges it with the static headers in netlify.toml.
 */
import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import type { Plugin } from 'vite'

const INLINE_SCRIPT = /<script\b([^>]*)>([\s\S]*?)<\/script>/gi

/** sha256-… sources for every classic inline <script> (no src, not a module). */
export function inlineScriptHashes(html: string): string[] {
  const hashes: string[] = []
  for (const match of html.matchAll(INLINE_SCRIPT)) {
    const attrs = match[1]
    const body = match[2]
    if (/\bsrc\s*=/i.test(attrs) || body.trim() === '') continue
    hashes.push(`'sha256-${createHash('sha256').update(body, 'utf8').digest('base64')}'`)
  }
  return hashes
}

/** Origin of the API URL; throws on anything but an absolute http(s) URL. */
export function apiOrigin(url: string): string {
  const parsed = new URL(url)
  if (parsed.protocol !== 'https:' && parsed.protocol !== 'http:') {
    throw new Error(`VITE_API_URL must be an http(s) URL, got ${parsed.protocol}`)
  }
  return parsed.origin
}

export function buildCsp(apiUrl: string, scriptHashes: string[]): string {
  return [
    "default-src 'self'",
    `script-src 'self' ${scriptHashes.join(' ')}`.trim(),
    "style-src 'self' 'unsafe-inline'",
    "img-src 'self' data: blob:",
    "font-src 'self'",
    `connect-src 'self' ${apiOrigin(apiUrl)}`,
    "frame-ancestors 'none'",
    "base-uri 'self'",
    "form-action 'none'",
  ].join('; ')
}

export function headersFile(csp: string): string {
  return `# Generated by build/csp.ts from VITE_API_URL and index.html. Do not edit.\n/*\n  Content-Security-Policy: ${csp}\n`
}

/** Vite plugin: write dist/_headers with the CSP once index.html is on disk. */
export function netlifyCsp(apiUrl: string): Plugin {
  return {
    name: 'gpradar-netlify-csp',
    apply: 'build',
    writeBundle(options) {
      const dir = options.dir ?? 'dist'
      const html = readFileSync(join(dir, 'index.html'), 'utf8')
      writeFileSync(join(dir, '_headers'), headersFile(buildCsp(apiUrl, inlineScriptHashes(html))))
    },
  }
}
